#!/usr/bin/env bash
# Last step of `make sync`, for both Data Pump and copy mode:
#   1. parent rows: when a table was limited (LIMIT/SAMPLE/WHERE/NONE), copy the
#      parent rows its foreign keys point to, repeating until no rows are missing
#      (so chains like order_items -> orders -> customers are followed);
#   2. foreign keys: create them from prod's dictionary (validated when the data
#      allows it, otherwise ENABLE NOVALIDATE with a warning);
#   3. identity columns: restore GENERATED ALWAYS and continue after the copied
#      values; then recompile the schema.
# Reads prod over a temporary database link; writes only to the local DB.
set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
# shellcheck source=scripts/lib.sh
source "$SCRIPT_DIR/lib.sh"
load_env
resolve_settings
require_vars APP_SCHEMA PROD_USER PROD_PASSWORD LOCAL_SYS_PASSWORD
require_prod_target
validate_identifier "$APP_SCHEMA" schema
validate_identifier "$PROD_USER" "prod user"
schema="$(upper "$APP_SCHEMA")"
using="$(prod_link_using)"
using_sql="${using//\'/\'\'}"
ensure_network
ensure_sqlcl_image

drop_link() {
  sqlcl_local system >/dev/null 2>&1 <<'SQL' || true
begin
  execute immediate 'drop database link PLSQL_SYNC_LINK';
exception when others then null;
end;
/
SQL
}
drop_link
trap drop_link EXIT

echo "==> following foreign keys: parent rows, constraints, identity columns"

out="$(sqlcl_local system <<SQL
create database link PLSQL_SYNC_LINK connect to $PROD_USER identified by "$PROD_PASSWORD" using '$using_sql';
set serveroutput on size unlimited
set heading off feedback off pagesize 0 linesize 32767
prompt __BEGIN__
declare
  type t_names is table of varchar2(128);
  added   number;
  total   number := 0;
  passes  pls_integer := 0;

  -- Quoted, comma separated key columns of a constraint on prod, with a prefix.
  function key_cols(p_cons varchar2, p_prefix varchar2) return varchar2 is
    v varchar2(32767);
  begin
    for c in (select column_name from all_cons_columns@PLSQL_SYNC_LINK
               where owner = '$schema' and constraint_name = p_cons order by position) loop
      v := v || case when v is not null then ', ' end || p_prefix || '"' || c.column_name || '"';
    end loop;
    return v;
  end;

  -- "a.x = b.y and ..." joining two key column lists position by position.
  function key_join(p_left_cons varchar2, p_left varchar2, p_right_cons varchar2, p_right varchar2) return varchar2 is
    l t_names; r t_names; v varchar2(32767);
  begin
    select column_name bulk collect into l from all_cons_columns@PLSQL_SYNC_LINK
     where owner = '$schema' and constraint_name = p_left_cons order by position;
    select column_name bulk collect into r from all_cons_columns@PLSQL_SYNC_LINK
     where owner = '$schema' and constraint_name = p_right_cons order by position;
    for i in 1 .. l.count loop
      v := v || case when i > 1 then ' and ' end
             || p_left || '."' || l(i) || '" = ' || p_right || '."' || r(i) || '"';
    end loop;
    return v;
  end;

  function table_cols(p_table varchar2, p_prefix varchar2) return varchar2 is
    v varchar2(32767);
  begin
    for c in (select column_name from all_tab_cols
               where owner = '$schema' and table_name = p_table
                 and virtual_column = 'NO' and hidden_column = 'NO'
                 and data_type not in ('LONG', 'LONG RAW') order by column_id) loop
      v := v || case when v is not null then ', ' end || p_prefix || '"' || c.column_name || '"';
    end loop;
    return v;
  end;

  procedure run(p_sql varchar2) is
  begin
    execute immediate p_sql;
  exception when others then
    dbms_output.put_line('warning: ' || sqlerrm || ' in: ' || substr(p_sql, 1, 200));
  end;

  -- Identity columns on prod (12c+; the view does not exist on 11g).
  procedure identity_cols(p_tables out t_names, p_cols out t_names, p_types out t_names) is
  begin
    execute immediate 'select table_name, column_name, generation_type from all_tab_identity_cols@PLSQL_SYNC_LINK where owner = :1'
      bulk collect into p_tables, p_cols, p_types using '$schema';
  exception when others then
    p_tables := t_names(); p_cols := t_names(); p_types := t_names();
  end;
begin
  declare
    it t_names; ic t_names; ig t_names;
  begin
    identity_cols(it, ic, ig);
    -- Parent rows are inserted with their prod key values.
    for i in 1 .. it.count loop
      run('alter table "$schema"."' || it(i) || '" modify ("' || ic(i) || '" generated by default as identity)');
    end loop;

    -- 1. Follow foreign keys and copy missing parent rows.
    loop
      passes := passes + 1;
      added := 0;
      for fk in (select c.table_name child, c.constraint_name cname, p.table_name parent, p.constraint_name pname
                   from all_constraints@PLSQL_SYNC_LINK c
                   join all_constraints@PLSQL_SYNC_LINK p
                     on p.owner = c.r_owner and p.constraint_name = c.r_constraint_name
                  where c.owner = '$schema' and c.constraint_type = 'R' and p.owner = '$schema'
                    and exists (select 1 from all_tables t where t.owner = '$schema' and t.table_name = c.table_name)
                    and exists (select 1 from all_tables t where t.owner = '$schema' and t.table_name = p.table_name)) loop
        begin
          execute immediate 'insert into "$schema"."' || fk.parent || '" (' || table_cols(fk.parent, '') || ')'
            || ' select ' || table_cols(fk.parent, 'r.') || ' from "$schema"."' || fk.parent || '"@PLSQL_SYNC_LINK r'
            || ' where exists (select 1 from "$schema"."' || fk.child || '" c where '
            || key_join(fk.cname, 'c', fk.pname, 'r') || ')'
            || ' and not exists (select 1 from "$schema"."' || fk.parent || '" l where '
            || key_join(fk.pname, 'l', fk.pname, 'r') || ')';
          if sql%rowcount > 0 then
            dbms_output.put_line('. . added ' || sql%rowcount || ' parent rows to "' || fk.parent || '" for "' || fk.child || '"');
            added := added + sql%rowcount;
          end if;
          commit;
        exception when others then
          rollback;
          dbms_output.put_line('warning: could not add parent rows to ' || fk.parent || ': ' || sqlerrm);
        end;
      end loop;
      total := total + added;
      exit when added = 0 or passes >= 20;
    end loop;

    -- 2. Foreign keys, validated when the data allows it.
    for fk in (select c.table_name child, c.constraint_name cname, c.delete_rule, c.status,
                      p.table_name parent, p.constraint_name pname
                 from all_constraints@PLSQL_SYNC_LINK c
                 join all_constraints@PLSQL_SYNC_LINK p
                   on p.owner = c.r_owner and p.constraint_name = c.r_constraint_name
                where c.owner = '$schema' and c.constraint_type = 'R' and p.owner = '$schema'
                  and exists (select 1 from all_tables t where t.owner = '$schema' and t.table_name = c.table_name)
                  and not exists (select 1 from all_constraints l
                                   where l.owner = '$schema' and l.constraint_name = c.constraint_name)) loop
      declare
        ddl varchar2(32767) := 'alter table "$schema"."' || fk.child || '" add constraint "' || fk.cname || '"'
          || ' foreign key (' || key_cols(fk.cname, '') || ') references "$schema"."' || fk.parent || '"'
          || ' (' || key_cols(fk.pname, '') || ')'
          || case fk.delete_rule when 'CASCADE' then ' on delete cascade' when 'SET NULL' then ' on delete set null' end;
      begin
        execute immediate ddl;
      exception when others then
        if sqlcode = -2298 then
          run(ddl || ' enable novalidate');
          dbms_output.put_line('warning: ' || fk.cname || ' created ENABLE NOVALIDATE (rows without a parent remain)');
        else
          dbms_output.put_line('warning: could not create ' || fk.cname || ': ' || sqlerrm);
        end if;
      end;
      if fk.status = 'DISABLED' then
        run('alter table "$schema"."' || fk.child || '" disable constraint "' || fk.cname || '"');
      end if;
    end loop;

    -- 3. Identity columns: same mode as prod, continuing after the copied values.
    for i in 1 .. it.count loop
      run('alter table "$schema"."' || it(i) || '" modify ("' || ic(i) || '" generated ' || ig(i)
          || ' as identity (start with limit value))');
    end loop;
  end;
  dbms_output.put_line('__PARENTS__ ' || total);
  dbms_utility.compile_schema('$schema', false);
end;
/
prompt __END__
SQL
)" || die "cannot connect to the local DB (run: make up)" 2

result="$(printf '%s\n' "$out" | between_markers || true)"
if [[ "$result" != *__PARENTS__* ]]; then
  printf '%s\n' "$out" | redact_secrets >&2
  die "could not link tables to their parent rows (is prod reachable from the local DB?)" 2
fi
printf '%s\n' "$result" | grep -v -e '^__PARENTS__' -e '^[[:space:]]*$' || true
echo "==> parent rows added: $(printf '%s\n' "$result" | sed -n 's/^__PARENTS__ //p')"
